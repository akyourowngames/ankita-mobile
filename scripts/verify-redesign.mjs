state.conversations[0].messages[1].tools = [{ id: 'preview-recall', name: 'memory_search', title: 'Recall memories', status: 'succeeded', arguments: '{"query":"weekly plan"}', result: '{"ok":true}', startedAt: Date.now(), finishedAt: Date.now() }];
