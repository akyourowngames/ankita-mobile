  await page.goto(`http://127.0.0.1:${web.address().port}`);
  await button('New conversation').waitFor();
  assert.equal(await page.getByRole('navigation', { name: 'Conversation history', exact: true }).count(), 1, 'Conversation navigation has a separate region');
  assert.equal(await page.getByRole('navigation', { name: 'Workspace', exact: true }).count(), 0, 'No extra navigation bars');
